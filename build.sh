#!/usr/bin/env bash
# Builds the Horizon Switch launcher: a homebrew app (.nro) on Borealis.
#
#   ./build.sh                      the toolchain image if it is missing, then the NRO
#   ./build.sh probe                the OpenGL probe (a tiny app that reports what GL the console gives)
#   ./build.sh clean                only the build output goes
#
# Needs Docker (or Podman) on Linux. It clones Borealis' `legacy` branch (the one every Switch
# homebrew UI uses) into ./.borealis at a pinned revision, and applies the two small patches the
# launcher needs from it.
#
# Optional: HORIZON_MSA_CLIENT_ID=<azure-app-id> bakes the Microsoft sign-in's app into the build.
# Without it the app reads the ID from Settings, or from HORIZON_MSA_CLIENT_ID in the game's env.txt.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$HERE"
APP="$HERE"

BOREALIS="${BOREALIS_PATH:-$HERE/.borealis}"
BOREALIS_REV=cbdc1b65314d1eeb2799deae5cf6f113d6d67b46
IMAGE=horizon-launcher-toolchain:local
ENGINE="${CONTAINER_ENGINE:-$(command -v docker >/dev/null && echo docker || echo podman)}"

clone_borealis() {
    if [ ! -d "$BOREALIS/.git" ]; then
        echo "==> cloning borealis (legacy) into $BOREALIS"
        git clone -q -b legacy https://github.com/natinusala/borealis.git "$BOREALIS"
        git -C "$BOREALIS" fetch -q --depth 1 origin "$BOREALIS_REV"
        git -C "$BOREALIS" checkout -q "$BOREALIS_REV"
    fi

    # The Appearance setting needs a theme setter, and one libnx call Borealis makes no longer
    # exists. Both patches are tiny and the revision above is pinned, so they apply cleanly; each is
    # skipped when it is already in.
    for patch in "$APP"/patches/*.patch; do
        if git -C "$BOREALIS" apply --reverse --check "$patch" 2>/dev/null; then
            continue # already applied
        fi
        git -C "$BOREALIS" apply "$patch"
        echo "==> applied $(basename "$patch") to borealis"
    done
}

image() {
    if ! "$ENGINE" image inspect "$IMAGE" >/dev/null 2>&1; then
        echo "==> building $IMAGE (the toolchain, once)"
        "$ENGINE" build -t "$IMAGE" -f "$APP/Containerfile" "$APP"
    fi
}

romfs() {
    # Borealis' own fonts, translations and icons, then the launcher's (drawn, not committed).
    mkdir -p "$APP/romfs"
    cp -r "$BOREALIS/resources/." "$APP/romfs/"
    mkdir -p "$APP/romfs/img"

    # The certificate bundle for HTTPS: the console has none of its own.
    if [ ! -f "$APP/romfs/cacert.pem" ]; then
        echo "==> fetching the CA bundle"
        curl -sSL -o "$APP/romfs/cacert.pem" https://curl.se/ca/cacert.pem
    fi

    python3 "$APP/make-assets.py"
}

# The Microsoft sign-in's Azure app, baked into the NRO when the build is given one. It goes in a
# generated header rather than a compiler flag so that changing it always rebuilds (make doesn't
# notice a changed flag, and would keep an old ID in the object file). The header is gitignored.
build_config() {
    mkdir -p "$APP/build"
    cat > "$APP/build/build_config.hpp" <<EOF
// Generated by build.sh. Not committed: it holds the build's own values.
#pragma once

#define HORIZON_LAUNCHER_CLIENT_ID "${HORIZON_MSA_CLIENT_ID:-}"
EOF
}

build() {
    image
    romfs
    build_config

    echo "==> building the NRO${HORIZON_MSA_CLIENT_ID:+ (with a Microsoft client ID)}"
    # BOREALIS_PATH is relative to the repository root (the Makefile prefixes it with TOPDIR), and
    # the container mounts the checkout inside it as `borealis`.
    "$ENGINE" run --rm --user "$(id -u):$(id -g)" -e HOME=/tmp \
        -v "$ROOT:/repo" -v "$BOREALIS:/repo/borealis" \
        -w /repo \
        -e DEVKITPRO=/opt/devkitpro \
        "$IMAGE" bash -lc 'make -j"$(nproc)" BOREALIS_PATH=borealis'

    echo
    echo "==> $APP/horizon-launcher.nro"
}

case "${1:-all}" in
    all) build ;;
    probe)
        image
        echo "==> building the OpenGL probe"
        "$ENGINE" run --rm --user "$(id -u):$(id -g)" -e HOME=/tmp \
            -v "$ROOT:/repo" -w /repo/gl-probe \
            -e DEVKITPRO=/opt/devkitpro \
            "$IMAGE" bash -lc 'make -j"$(nproc)"'
        echo "==> $APP/gl-probe/gl-probe.nro"
        ;;
    clean)
        make -C "$APP" clean || true
        make -C "$APP/gl-probe" clean || true
        ;;
    *) echo "usage: $0 [all|probe|clean]" >&2; exit 2 ;;
esac
